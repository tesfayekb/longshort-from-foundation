/**
 * Fill snapshot. `filled: true` requires `filled_qty === requested_qty`
 * (atomic fill; partial-fill branch deferred to the analog of DW-140).
 */
export interface BrokerFillResult {
  order_id: string;
  filled: boolean;
  filled_qty: number;
  avg_fill_price: number | null;
  fetched_at: Date;
}

export interface BrokerFillFetcher {
  fetchFill(order_id: string, ts: Date): Promise<BrokerFillResult>;
}

