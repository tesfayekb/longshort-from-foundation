// ────────────────────────────────────────────────────────────────────
// Position surface (adapter: alpaca-position-fetcher.ts)
// ────────────────────────────────────────────────────────────────────

/** Position snapshot as returned by the broker. */
export interface BrokerPosition {
  symbol: string;
  /** Signed: negative for short positions. */
  qty: number;
  /** Dollars per share. */
  avg_entry_price: number;
  /** Broker-stamped snapshot time (derived from injected `ts`). */
  fetched_at: Date;
  /** Dollars; signed (negative for shorts). Alpaca /v2/positions native. */
  market_value?: number;
  /** Dollars per share; last mark. Alpaca /v2/positions native. */
  current_price?: number;
  /** Dollars; since-fill unrealized P&L per Alpaca. Typed-absence — NEVER fabricated 0. */
  unrealized_pl?: number;
  /** Dollars; today's session unrealized P&L per Alpaca. Typed-absence. */
  unrealized_intraday_pl?: number;
  /** Dollars per share; prior session close per Alpaca. Typed-absence. */
  lastday_price?: number;
}

export interface BrokerPositionFetcher {
  /**
   * Fetch position for one symbol. Throws on network/auth errors. Returns
   * `null` ONLY if the broker explicitly reports the symbol has NO position
   * (not a fetch failure).
   */
  fetchPosition(symbol: string, ts: Date): Promise<BrokerPosition | null>;

  /**
   * List every currently-open broker position. Throws on network/auth errors.
   * Live impl MUST populate {market_value, current_price} on every row.
   */
  listOpenPositions?(ts: Date): Promise<BrokerPosition[]>;
}

// ────────────────────────────────────────────────────────────────────
// Shortability surface (adapter: alpaca-shortability-fetcher.ts)
// ────────────────────────────────────────────────────────────────────

/** Per-symbol shortability snapshot. Pre-trade gate for SHORT entries. */
export interface BrokerShortability {
  symbol: string;
  /**
   * Authoritative pre-trade gate. Alpaca composes ETB-list membership +
   * marginability into this single boolean.
   */
  shortable: boolean;
  /** Diagnostic — surfaced into reconciliation payloads only. */
  easy_to_borrow: boolean | null;
  fetched_at: Date;
}

export interface BrokerShortabilityFetcher {
  /**
   * Fetch shortability for one symbol. Throws on 5xx/network/auth errors
   * (DEC-034 (3) propagation). Inactive / delisted / unknown-symbol
   * returns `shortable: false` EXPLICITLY — never default-on-failure.
   */
  fetchShortability(symbol: string, ts: Date): Promise<BrokerShortability>;
}

// ────────────────────────────────────────────────────────────────────
// Order submission surface (adapter: alpaca-order-submitter.ts)
// ────────────────────────────────────────────────────────────────────

export interface BrokerOrderRequest {
  symbol: string;
  /** Integer whole shares. */
  qty: number;
  side: 'buy' | 'sell';
  /** `limit` for standard entries. `market` reserved for parallel-cover legs. */
  type: 'limit' | 'market';
  /** TIF=DAY. */
  time_in_force: 'day';
  /** Dollars; > 0 for limit; ignored for market. */
  limit_price: number;
  /** Per-target-per-tick idempotency key (generated by the submitter caller). */
  client_order_id: string;
}

/** Broker response on successful POST. Equivalent to Alpaca /v2/orders 200 subset. */
export interface BrokerOrderAcceptance {
  order_id: string;
  client_order_id: string;
  /** Broker-reported lifecycle: 'new' / 'pending_new' / 'accepted' / etc. */
  status: string;
  /** Broker-side acceptance timestamp. */
  submitted_at: Date;
}

export interface BrokerOrderSubmitter {
  submitOrder(req: BrokerOrderRequest, ts: Date): Promise<BrokerOrderAcceptance>;
}

