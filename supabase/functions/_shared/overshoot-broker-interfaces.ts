/**
 * Order cancellation. Required for the W3.8 marketable-limit cancel-and-
 * replace escalation (submit-without-cancel is incomplete broker parity;
 * canceller authorized by name in the W3.2.a operator ruling). Idempotent
 * at the broker boundary — cancelling an already-terminal order is a no-op
 * (adapter maps 422 → no-op per Alpaca's terminal-order semantics).
 */
export interface BrokerOrderCanceller {
  cancelOrder(order_id: string, ts: Date): Promise<void>;
}